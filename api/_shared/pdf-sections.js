/** 식이제한 배지 색 — 일반과 시각적으로 반드시 달라야 한다(오독 = 안전 사고). */
const STYLE_COLOR = { halal: '#15803d', vegan: '#0369a1' };

/**
 * itinerary.recommended_restaurants → PDF HTML 섹션.
 * @returns HTML string. 데이터가 아예 없으면 '' (섹션 자체를 그리지 않음).
 */
export function buildRecommendedRestaurantsSection(itinerary, lang, C) {
  const raw = itinerary && itinerary.recommended_restaurants;
  if (!raw || (typeof raw === 'object' && !Array.isArray(raw) && Object.keys(raw).length === 0)) return '';

  const styleMap = Array.isArray(raw) ? { general: raw } : raw;

  const buckets = [];
  for (const style of REC_BUCKET_ORDER) {
    if (Array.isArray(styleMap[style])) buckets.push({ style, list: styleMap[style] });
  }
  for (const [style, list] of Object.entries(styleMap)) {
    if (!REC_BUCKET_ORDER.includes(style) && Array.isArray(list) && list.length > 0) {
      buckets.push({ style, list });
    }
  }
  if (!buckets.some((b) => b.list.length > 0)) return '';

  const ll = REC_L4[String(lang || 'en')] || REC_L4.en;
  const isKo = lang === 'ko';
  const styleLabel = (style) => ll[style] || (style.charAt(0).toUpperCase() + style.slice(1));

  let html = `<div style="margin-bottom:20px;page-break-inside:avoid;" class="pdf-rec-restaurants">
    <h3 style="font-size:15px;font-weight:700;color:${C.heading};margin:0 0 4px;">${escapeHtml(ll.title)}</h3>
    <p style="font-size:10px;color:${C.muted};margin:0 0 12px;">${escapeHtml(ll.subtitle)}</p>`;

  for (const { style, list } of buckets) {
    const color = STYLE_COLOR[style] || C.accent;
    html += `<div style="margin-bottom:14px;">
      <div style="display:inline-block;font-size:10px;font-weight:700;color:white;background:${color};padding:2px 8px;border-radius:3px;margin-bottom:8px;">${escapeHtml(styleLabel(style))}</div>`;

    if (!list || list.length === 0) {
      // 식이제한 bucket 이 비었으면 반드시 그 사실을 적는다 — 침묵이 가장 위험하다.
      if (style !== 'general') {
        html += `<p style="font-size:10px;color:${C.muted};margin:0 0 4px;">${escapeHtml(ll.noneForDiet)}</p>`;
      }
      html += '</div>';
      continue;
    }

    const CARDS_PER_PAGE = 6;
    html += '<table style="width:100%;border-collapse:collapse;">';
    list.forEach((r, idx) => {
      const displayName = isKo ? r.name : (r.nameEn || r.name);
      const cuisine = isKo ? (r.cuisineKo || r.cuisine) : (r.cuisine || r.cuisineKo);
      const district = isKo ? (r.dong || '') : (r.dongEn || r.dong || '');
      const breakClass = idx > 0 && idx % CARDS_PER_PAGE === 0 ? ' class="pdf-day-break"' : '';
      const meta = [
        cuisine,
        district,
        r.reviewCount !== undefined ? `${Number(r.reviewCount).toLocaleString()} ${ll.reviews}` : '',
        r.nearestStopKm !== undefined ? `${r.nearestStopKm}${ll.kmAway}` : '',
      ].filter(Boolean).join(' · ');

      html += `<tr${breakClass}>
        <td style="padding:4px 0;vertical-align:top;">
          <div style="background:${C.cardBg};border:1px solid ${C.border};border-left:3px solid ${color};border-radius:6px;padding:8px 10px;margin-bottom:6px;page-break-inside:avoid;break-inside:avoid;">
            <table style="width:100%;border-collapse:collapse;"><tr>
              <td style="vertical-align:top;padding:0;">
                <p style="font-size:12px;font-weight:700;color:${C.heading};margin:0;">${escapeHtml(displayName || '')}</p>
                ${!isKo && r.name && r.name !== displayName ? `<p style="font-size:10px;color:${C.muted};margin:1px 0 0;">${escapeHtml(r.name)}</p>` : ''}
              </td>
              ${r.rating ? `<td style="vertical-align:top;text-align:right;padding:0 0 0 6px;white-space:nowrap;"><span style="font-size:11px;font-weight:700;color:#b45309;">&#9733; ${Number(r.rating).toFixed(1)}</span></td>` : ''}
            </tr></table>
            <p style="font-size:10px;color:${C.sub};margin:3px 0 0;">${escapeHtml(meta)}</p>
            ${r.address ? `<p style="font-size:9px;color:${C.muted};margin:2px 0 0;">${escapeHtml(r.address)}</p>` : ''}
            ${r.googleMapsUrl ? `<p style="font-size:9px;margin:3px 0 0;"><a href="${escapeHtml(r.googleMapsUrl)}" style="color:${color};text-decoration:underline;">${escapeHtml(ll.openMap)}</a></p>` : ''}
          </div>
        </td>
      </tr>`;
    });
    html += '</table></div>';
  }

  return `${html}</div>`;
}

/**
 * itinerary.budget_breakdown → 일자별 예산표 + 합계.
 * @returns HTML string. 행이 없으면 ''.
 */
export function buildBudgetTableHtml(budget, lang, C) {
  const rows = Array.isArray(budget) ? budget : [];
  if (rows.length === 0) return '';
  const L = pdfLabels(lang);

  let html = `<div style="margin-bottom:20px;page-break-inside:avoid;">
    <h3 style="font-size:15px;font-weight:700;color:${C.heading};margin:0 0 10px;">${escapeHtml(L.budgetSummary)}</h3>
    <table style="width:100%;font-size:11px;border-collapse:collapse;border:1px solid ${C.border};">
      <tr style="background:${C.accent};color:white;">
        <th style="text-align:left;padding:8px;">${escapeHtml(L.day)}</th>
        <th style="text-align:right;padding:8px;">${escapeHtml(L.transport)}</th>
        <th style="text-align:right;padding:8px;">${escapeHtml(L.entry)}</th>
        <th style="text-align:right;padding:8px;">${escapeHtml(L.meals)}</th>
        <th style="text-align:right;padding:8px;">${escapeHtml(L.total)}</th>
      </tr>`;

  rows.forEach((row, i) => {
    html += `<tr style="background:${i % 2 === 0 ? '#fff' : C.cardBg};border-bottom:1px solid ${C.border};">
      <td style="padding:6px 8px;font-weight:600;">${escapeHtml(L.day)} ${escapeHtml(String(row.day != null ? row.day : i + 1))}</td>
      <td style="text-align:right;padding:6px 8px;">${formatKRW(row.transport_krw || 0)}</td>
      <td style="text-align:right;padding:6px 8px;">${formatKRW(row.entry_fees_krw || 0)}</td>
      <td style="text-align:right;padding:6px 8px;">${formatKRW(row.meals_krw || 0)}</td>
      <td style="text-align:right;padding:6px 8px;font-weight:700;color:${C.accent};">${formatKRW(row.total_krw || 0)}</td>
    </tr>`;
  });

  const grandTotal = rows.reduce((s, r) => s + (r.total_krw || 0), 0);
  html += `<tr style="background:${C.accent};color:white;font-weight:700;">
      <td style="padding:8px;" colspan="4">${escapeHtml(L.total)}</td>
      <td style="text-align:right;padding:8px;">${formatKRW(grandTotal)}</td>
    </tr></table></div>`;
  return html;
}
